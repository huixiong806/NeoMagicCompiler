# 3-4 参考解：用状态机数"合法咒文词"的个数（字母开头 + 字母/数字）
#
# 词法规定（叙事里的"伊塔尔规定"，一字不多一字不少）：
#   把输入按**分隔符**切成一段段；一段里只含字母和数字，就叫一个"词"；
#   词的首字符是字母 → 合法咒文词；首字符是数字 → 不算。
#   **分隔符 = 一切不是字母、也不是数字的字符**（空格、逗号、问号、下划线、换行……）。
#   所以：
#     `abc`、`x9`、`a1b2c3`、`A`   → 合法（各算 1 个）
#     `9x`                        → 不算（数字开头）
#     `x_y`                       → 算 2 个！下划线是分隔符，它把 `x` 和 `y` 切成两段，
#                                   两段都是字母开头，都合法。
#                                   （这一点最容易想歪：把它想成"词被弄坏了"。
#                                     机器的规矩很机械：不是字母数字 = 分隔符。）
#
# 状态定义（三个开关）：
#   x8  = 1：已经进词（这个词的首字符已经处理过，后面的字符走"后续字符"分支）
#   x9  = 1：到目前为止这个词是合法的（首字符是字母，后面也只出现字母数字）
#   x12 = 1：这个词**中途被弄坏过**（出现了不是字母数字的字符 —— 它同时是分隔符，
#           所以这个词就此结束，后面的字符不许接在它后面"复活"）
#   三个都是 0：正处在两个词之间（等着下一个词的首字符）
#
# 为什么必须有 x12：只靠 x8 的话，被弄坏的词会"复活" ——
#   `a9_x` 里 `_` 把 `a9` 结算掉（x9 清 0），下一个 'x' 会发现 x8 还是 1、x9 是 0，
#   于是又被当成一个新词的首字符，数出多余的一个。x12 记住"这个词已经结束了"
#   （要么结算过、要么废过），'x' 一看就知道自己必须等真正的分隔符复位。
#
# 判定规则：
#   普通字符（字母/数字）：
#     x8 = 0（在两词之间） → 它是首字符：字母 → x9 = 1；数字 → x9 保持 0（没资格）
#     x8 = 1（在词里）     → 后续字符：还合法的话，字母数字都安全；别的弄坏它
#   分隔符（不是字母数字的一切）：
#     先收尾（还合法才给个数加一），再回到"两词之间"
#   读到 0（输入结束）：也要收尾一次 —— 输入可能正好停在一个词中间
#
# 结果既打印出来，也写进 0x2000。

li   x1, 0xF0000004      # 输入端口
li   x21, 0xF0000000     # 显示端口
li   x20, 10             # 换行符
addi x8, x0, 0           # 还没进词
addi x9, x0, 0           # 这个词还不合法
addi x12, x0, 0          # 这个词没被弄坏过
addi x18, x0, 0          # 合法词计数

loop:
lw   x5, 0(x1)           # 取下一个字符
beq  x5, x0, finish      # 输入结束 → 收尾
# ── 先问：这个字符是不是"普通字符"（字母或数字）？不是的话它就是分隔符 ──
li   x6, 48              # '0'
blt  x5, x6, delimiter   # 比 '0' 小 → 分隔符
li   x6, 57              # '9'
blt  x6, x5, maybe_letter
j    word_char           # 是数字 → 普通字符
maybe_letter:
li   x6, 65              # 'A'
blt  x5, x6, delimiter   # 空档 `: ; < = > ? @` → 分隔符
li   x6, 90              # 'Z'
blt  x6, x5, after_upper # 比 'Z' 大 → 可能是小写，也可能掉进空档
j    word_char           # 是大写字母 → 普通字符
after_upper:
li   x6, 97              # 'a'
blt  x5, x6, delimiter   # 空档 `[ \ ] ^ _ \`` → 分隔符
li   x6, 122             # 'z'
blt  x6, x5, delimiter   # 比 'z' 大 → 分隔符
j    word_char           # 是小写字母 → 普通字符

# ══ 普通字符：先看自己在词的哪个位置 ══
word_char:
bne  x8, x0, later_char  # 已经在词里 → 走后续字符分支
addi x8, x0, 1           # 两词之间 → 它是新词的首字符
li   x6, 65              # 上面已经排除了数字，这里只要问"是不是字母"
blt  x5, x6, loop        # 落进空档 → 这个词没资格（x9 保持 0）
li   x6, 90
ble  x5, x6, first_letter
li   x6, 97
blt  x5, x6, loop
li   x6, 122
blt  x6, x5, loop
first_letter:
addi x9, x0, 1           # 首字符是字母 → 这个词有资格
j    loop

later_char:
bne  x12, x0, loop       # 这个词已经被弄坏过 → 后面的字符都救不回它
li   x6, 65              # 后面还是字母吗？
blt  x5, x6, later_gap
li   x6, 90
ble  x5, x6, loop        # 大写字母 → 仍然合法
li   x6, 97
blt  x5, x6, later_gap
li   x6, 122
ble  x5, x6, loop        # 小写字母 → 仍然合法
later_gap:
li   x6, 48              # 空档里的符号：只有数字能救它
blt  x5, x6, later_bad
li   x6, 57
blt  x6, x5, later_bad
j    loop                # 是数字 → 仍然合法
later_bad:
addi x9, x0, 0           # 这个词作废
addi x12, x0, 1          # 记下"已经被弄坏过"，别让后面的字母重新开始
j    loop

# ══ 分隔符：先收尾，再回到两词之间 ══
delimiter:
beq  x9, x0, reset       # 只有"目前还合法"的词才算数
addi x18, x18, 1
reset:
addi x8, x0, 0
addi x9, x0, 0
addi x12, x0, 0
j    loop

finish:
beq  x9, x0, report      # 输入正好停在一个词中间：也要给它收尾
addi x18, x18, 1
report:
li   x9, 0x2000
sw   x18, 0(x9)          # 合法词个数写进 0x2000
addi x10, x18, 0         # 待打印的数放 x10（a0）
li   x17, 2              # x17（a7） = 2：按十进制打印
ecall
sb   x20, 0(x21)         # 补一个换行
li   x10, 0
li   x17, 0
ecall
