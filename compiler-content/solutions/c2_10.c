// 2-10 参考解：数一数 x 的二进制里有几个 1
//
// 注意用**逻辑右移**（把最高位补 0）。如果用算术右移，负数会一直保持负数、
// 永远移不到 0，循环就出不来了 —— 0xFFFFFFFF 那一组就是专门检查这个的。
// 星咒里 `x >> 1` 对 int 是按位右移，符号位补 0，正合这里的要求。
int solve(int x) {
    int count = 0;
    while (x != 0) {
        if ((x & 1) != 0) {
            count = count + 1;
        }
        x = x >> 1;
    }
    return count;
}
