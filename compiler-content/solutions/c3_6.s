# 3-6 参考解：读入一行只有加法和减法的表达式，输出求值结果
#
# 约定（叙事里讲过）：
#   输入端口 0xF0000004，读回 0 表示结束
#   没遇到运算符之前，数字还可能变长：值 = 值 * 10 + (字符 - 48)
#   遇到 '+' 或 '-' 时，**先把这个数按刚读到的运算符并进总和，再换运算符**：
#       '+' → 总和 = 总和 + 值      （add）
#       '-' → 总和 = 总和 - 值      （sub）
#   读完输入时，手上那个数还没并进去 —— 按 x10 记着的"最后一次读到的运算符"并一次
#   结果写进 0x2000，用 a7 = 2 打印出来（会自动带负号）
#
# 关键点（这一关最容易写错的地方）：
#   "运算符管的是它**后面**那个数"，所以遇到运算符时并没有到结算的时机 ——
#   真正要结算的是"已经读完的这个数"，用的是**上一个**运算符。
#   最清楚的写法是：把"当前运算符"记在 x10 里，每读完一个数就用它结一次，
#   初始时 x10 = 1（相当于表达式最前面有一个隐式的 '+'，这样 -5+3 这种以负号开头的
#   表达式也能直接得到 总和 = 0 - 5 = -5）。
#
# 寄存器用法：
#   x19 = 输入端口     x5 = 当前字符     x6 = 临时常数
#   x9  = 正在拼的数   x10 = 当前运算符（1 = 加，-1 = 减）
#   x11 = 结算用的临时变量            x18 = 总和        x7 = 写结果用的地址
#   x1  = 子程序返回地址（所以输入端口不能占 x1）
#
# 踩过的坑（留个记录）：
#   `1+2-3+4` 曾经算出 6 —— 因为结算时用错了运算符（把每个运算符用在了它后面的数上，
#   导致 +1 被丢掉、而最后一项的符号错误）。差一点点就"看着像对"。

li   x19, 0xF0000004     # 输入端口
li   x21, 0xF0000000     # 显示端口（下面 print_int 里也是这个地址）
addi x18, x0, 0          # 总和
addi x9, x0, 0           # 正在拼的数
addi x10, x0, 1          # 当前运算符：表达式最前面视作有一个 '+'

eval_loop:
lw   x5, 0(x19)          # 取下一个字符
beq  x5, x0, eval_end

li   x6, 43              # '+' 是 43
beq  x5, x6, op_plus
li   x6, 45              # '-' 是 45
beq  x5, x6, op_minus

# ── 别的字符：只可能是数字，把它接到 x9 的尾巴上 ──
#    注意：一行表达式的末尾常常跟着一个换行符（10），它不是数字，
#    所以这里要真的检查"是不是数字"，不能假定"只要不是运算符就是数字"。
li   x6, 48              # '0'
blt  x5, x6, eval_end    # 比 '0' 小（空格、换行…）→ 表达式到头了
li   x6, 57              # '9'
blt  x6, x5, eval_end    # 比 '9' 大 → 也到头了
li   x6, 10
mul  x9, x9, x6          # 值 = 值 * 10
addi x5, x5, -48         # 字符 → 数字
add  x9, x9, x5
j    eval_loop

# ── 遇到运算符：先把刚刚读完的那个数并进总和，再换运算符 ──
op_plus:
mul  x11, x10, x9        # 按**当前**运算符结算（x10 = 1 → 加，-1 → 减）
add  x18, x18, x11
addi x9, x0, 0           # 手上的数清空，等下一个数
addi x10, x0, 1          # 当前运算符换成 '+'
j    eval_loop

op_minus:
mul  x11, x10, x9
add  x18, x18, x11
addi x9, x0, 0
addi x10, x0, -1         # 当前运算符换成 '-'
j    eval_loop

# ── 收尾：最后那个数还没结算，按 x10 记着的运算符再结一次 ──
eval_end:
mul  x11, x10, x9
add  x18, x18, x11

li   x7, 0x2000
sw   x18, 0(x7)          # 结果写进 0x2000
addi x10, x18, 0         # 传给打印子程序的参数（x10 就是 a0）
jal  x1, print_int

li   x10, 0
li   x17, 0
ecall

# ── 子程序：把 x10 里的整数打印出来（负数前面带 '-'） ──
#    借 0x2021 往下的那一小段当缓冲区：先反复"取最低位（余 10）、再除 10"把数字
#    从后往前存，再从前往后一个字符一个字符送出去。
#    只用 x3/x4/x6/x10/x12/x14/x17，**绝不碰 x9/x11/x18**（它们是外面算式的变量）。
print_int:
addi x14, x0, 0          # x14 = 1 表示这个数是负的
bge  x10, x0, pi_positive
li   x14, 1
sub  x10, x0, x10        # 取绝对值：0 - x
pi_positive:
li   x3, 0x2021          # 缓冲区末尾（正数最多 10 位，所以够放）
addi x6, x3, 0           # x6 = 写入位置，从后往前挪
li   x4, 10              # 除数

pi_digit:
remu x12, x10, x4        # 最低位数字
addi x12, x12, 48        # 数字 → 字符
addi x6, x6, -1
sb   x12, 0(x6)
divu x10, x10, x4        # 去掉最低位
bne  x10, x0, pi_digit   # 还没除尽 → 继续

beq  x14, x0, pi_emit
addi x6, x6, -1          # 负数：在高位左边补一个 '-'
li   x12, 45
sb   x12, 0(x6)

pi_emit:
li   x17, 1              # x17（a7） = 1：输出一个字符
pi_out:
lb   x12, 0(x6)          # 从最高位开始，一个字符一个字符送出去
beq  x12, x0, pi_done
addi x10, x12, 0
ecall
addi x6, x6, 1
j    pi_out
pi_done:
li   x10, 10             # 收尾补一个换行
ecall
jalr x0, 0(x1)
